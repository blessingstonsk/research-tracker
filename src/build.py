import json, pathlib
D = pathlib.Path(__file__).parent
read = lambda f: (D / f).read_text(encoding='utf-8')
css = read('style.css')
js = '\n'.join(read(f) for f in ['core.js', 'store.js', 'charts.js', 'scene3d.js', 'forms.js', 'views1.js', 'views2.js', 'views3.js', 'views4.js', 'sheetspec.js', 'gsync.js', 'main.js'])
page = f'''<title>PhD Research Tracker</title>
<meta name="claude:viewport-fit-sides" content="cover">
<meta name="description" content="Daily log, research plan, literature, experiments, writing, meetings and reports for a PhD on explainable vision-language models for autonomous driving.">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Poppins:wght@500;600;700;800&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;1,400&family=JetBrains+Mono:wght@400;500;600&display=swap">
<style>
{css}
</style>
<div id="app"><div class="loading">Loading Research Tracker…</div></div>
<script src="https://cdnjs.cloudflare.com/ajax/libs/xlsx/0.18.5/xlsx.full.min.js"></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/jspdf/2.5.1/jspdf.umd.min.js"></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>
<script>
{js}
</script>
'''
out = D / 'dist'; out.mkdir(exist_ok=True)
write = lambda p, s: p.write_text(s, encoding='utf-8')
write(out / 'index.html', page)
write(out / 'local.html', '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>' + page + '</body></html>')

# Google Apps Script web app: paste these files into the sheet's Extensions → Apps Script project
gas = out / 'gas'; gas.mkdir(exist_ok=True)
write(gas / 'Index.html', '<!doctype html><html><head><meta charset="utf-8"></head><body>' + page + '</body></html>')
write(gas / 'Code.gs', read('gas/Code.gs'))
write(gas / 'Lib.gs', '/* core.js + sheetspec.js, shared with the web page (generated by build.py) */\n' + read('core.js') + '\n' + read('sheetspec.js'))
write(gas / 'appsscript.json', json.dumps({'timeZone': 'Asia/Kolkata', 'runtimeVersion': 'V8', 'exceptionLogging': 'STACKDRIVER',
  'oauthScopes': ['https://www.googleapis.com/auth/spreadsheets.currentonly'],
  'webapp': {'executeAs': 'USER_DEPLOYING', 'access': 'MYSELF'}}, indent=2))
print('built', len(page))
